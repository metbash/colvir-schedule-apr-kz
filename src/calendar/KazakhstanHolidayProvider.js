    /**
     * Проверка праздничного дня.
     *
     * @param {Date} date
     * @returns {boolean}
     */
    isHoliday(date) {

        const key = this.toKey(date);

        return this.holidays.has(key);

    }

    /**
     * Преобразовать дату в YYYY-MM-DD.
     *
     * @param {Date} date
     * @returns {string}
     */
    toKey(date) {

        const year = date.getFullYear();

        const month = String(
            date.getMonth() + 1
        ).padStart(2, "0");

        const day = String(
            date.getDate()
        ).padStart(2, "0");

        return `${year}-${month}-${day}`;

    }

